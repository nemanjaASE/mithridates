"""Creates the accounts, the schema and the data. Runs once, as admin, before the app.

- `lab_legacy`: SELECT on `users` and `secrets`, used by the vulnerable variant.
- `lab_app`: SELECT on the columns of `users` the safe variant needs.
- Both are read-only and have a `statement_timeout`.
"""
import psycopg
from psycopg import sql

from .connection_settings import DatabaseCredentials
from .database import PostgresDatabase

# Passwords are stored ONLY as a bcrypt hash (pgcrypto: crypt() + gen_salt('bf')).
# Both login variants verify the password in SQL via crypt(); the only difference is
# that the vulnerable one concatenates the input while the safe one parameterizes it.
# id is a native `uuid` with DEFAULT uuidv7() (PostgreSQL 18+): a time-ordered prefix
# (good B-tree index locality) + a random tail (not enumerable), smaller than text.
_SCHEMA = """
CREATE EXTENSION IF NOT EXISTS pgcrypto;

DROP TABLE IF EXISTS users, secrets;

CREATE TABLE users (
    id            uuid PRIMARY KEY DEFAULT uuidv7(),
    username      TEXT NOT NULL UNIQUE,
    email         TEXT NOT NULL,
    role          TEXT NOT NULL,
    password_hash TEXT NOT NULL   -- bcrypt hash (pgcrypto); never a plaintext password
);

CREATE TABLE secrets (
    id    uuid PRIMARY KEY DEFAULT uuidv7(),
    name  TEXT NOT NULL,
    value TEXT NOT NULL
);
"""

# Lab data. id is generated by the database (uuidv7()); the password is hashed on insert.
# (username, email, role, password)
SEED_USERS = (
    ("mjovanovic", "milica.jovanovic@akme.rs", "user", "Leto2026!"),
    ("spetrovic", "stefan.petrovic@akme.rs", "user", "Beograd#92"),
    ("jkovac", "jelena.kovac@akme.rs", "editor", "Urednik!7"),
    ("admin", "admin@akme.rs", "admin", "S3cr3tAdminPass!"),
)
# (name, value)
SEED_SECRETS = (
    ("stripe_api_key", "sk-lab-DEMO-0000-DO-NOT-USE"),
    ("db_root_password", "root:labonly"),
    ("flag", "FLAG{sql_injection_demo}"),
)
_STATEMENT_TIMEOUT = "5s"
# Lower bcrypt cost: enough for a lab, keeps seeding fast. Raise for production.
_BCRYPT_SALT = "gen_salt('bf', 8)"


def reset_database(admin: PostgresDatabase, legacy: DatabaseCredentials, app: DatabaseCredentials) -> None:
    """Drops and recreates the schema, the accounts and the data.

    Args:
        admin: Connections for the admin account.
        legacy: The `lab_legacy` account to create.
        app: The `lab_app` account to create.
    """
    with admin.connect() as conn, conn.transaction():
        for credentials in (legacy, app):
            _ensure_login_role(conn, credentials)
        conn.execute(_SCHEMA)
        conn.cursor().executemany(
            "INSERT INTO users (username, email, role, password_hash) "
            f"VALUES (%s, %s, %s, crypt(%s, {_BCRYPT_SALT}))",
            SEED_USERS,
        )
        conn.cursor().executemany("INSERT INTO secrets (name, value) VALUES (%s, %s)", SEED_SECRETS)
        _grant_privileges(conn, legacy=sql.Identifier(legacy.user), app=sql.Identifier(app.user))


def _ensure_login_role(conn: psycopg.Connection, credentials: DatabaseCredentials) -> None:
    """Creates the login role, or updates its password if it exists."""
    role = sql.Identifier(credentials.user)
    exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (credentials.user,)).fetchone()
    if not exists:
        conn.execute(sql.SQL("CREATE ROLE {} LOGIN").format(role))
    conn.execute(
        sql.SQL("ALTER ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD {}").format(
            role, sql.Literal(credentials.password)
        )
    )
    conn.execute(sql.SQL("ALTER ROLE {} SET default_transaction_read_only = on").format(role))
    conn.execute(
        sql.SQL("ALTER ROLE {} SET statement_timeout = {}").format(role, sql.Literal(_STATEMENT_TIMEOUT))
    )


def _grant_privileges(conn: psycopg.Connection, legacy: sql.Identifier, app: sql.Identifier) -> None:
    """Grants each account the privileges it needs and nothing more."""
    database = sql.Identifier(conn.info.dbname)
    statements = (
        sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(database),
        sql.SQL("REVOKE ALL ON SCHEMA public FROM PUBLIC"),
        sql.SQL("GRANT CONNECT ON DATABASE {} TO {}, {}").format(database, legacy, app),
        sql.SQL("GRANT USAGE ON SCHEMA public TO {}, {}").format(legacy, app),
        sql.SQL("GRANT SELECT ON users, secrets TO {}").format(legacy),
        sql.SQL("GRANT SELECT (id, username, role, password_hash) ON users TO {}").format(app),
    )
    for statement in statements:
        conn.execute(statement)
